import type { ReceiptContext } from '../logic/receipts';
import { receiptNumberText } from '../logic/receipts';
import { paymentMethodLabel, paymentState } from '../logic/payments';
import { formatMoney } from '../logic/format';

/** The receipt itself (A5). Plain black-on-white so it prints and exports cleanly. */
export function ReceiptDocument({ ctx }: { ctx: ReceiptContext }) {
  const { payment: p, currency, settings } = ctx;
  const state = paymentState(p);
  const landlord = settings.landlord;
  const stamp = state === 'void' ? 'VOID' : state === 'bounced' ? 'BOUNCED' : state === 'pending' ? 'PENDING CLEARANCE' : null;

  return (
    <article className="receipt-doc relative bg-white text-black font-sans text-[12px] leading-snug p-6 max-w-[148mm] mx-auto">
      {stamp && (
        <div
          aria-hidden="true"
          className={`absolute inset-0 flex items-center justify-center pointer-events-none select-none ${
            state === 'pending' ? 'text-amber-600/25' : 'text-red-600/25'
          }`}
        >
          <span className="text-5xl font-black tracking-widest -rotate-[24deg] border-8 border-current px-4 py-1 rounded-lg">
            {stamp}
          </span>
        </div>
      )}

      <header className="flex items-start justify-between gap-4 pb-3 border-b-2 border-black">
        <div>
          <div className="text-base font-black">{landlord?.name || 'Rent Receipt'}</div>
          {landlord?.address && <div className="whitespace-pre-line">{landlord.address}</div>}
          {landlord?.phone && <div>Tel: {landlord.phone}</div>}
        </div>
        <div className="text-right">
          <div className="text-lg font-black tracking-wide">RECEIPT</div>
          <div className="font-mono font-bold">{receiptNumberText(ctx)}</div>
          <div>Date: {p.date}</div>
        </div>
      </header>

      <dl className="mt-4 grid grid-cols-[auto_1fr] gap-x-4 gap-y-1.5">
        <dt className="font-semibold">Received from</dt>
        <dd>{ctx.tenantName}</dd>
        <dt className="font-semibold">Property</dt>
        <dd>{ctx.unitLabel}</dd>
        <dt className="font-semibold">Payment method</dt>
        <dd>{paymentMethodLabel(p) || 'Not recorded'}</dd>
        {p.cheque && (
          <>
            <dt className="font-semibold">Cheque</dt>
            <dd>
              #{p.cheque.number}
              {p.cheque.bank ? `, ${p.cheque.bank}` : ''}, dated {p.cheque.date}
            </dd>
          </>
        )}
        {p.note && (
          <>
            <dt className="font-semibold">Note</dt>
            <dd>{p.note}</dd>
          </>
        )}
      </dl>

      <div className="mt-4 flex items-center justify-between border-2 border-black rounded-md px-4 py-3">
        <span className="font-semibold">Amount received</span>
        <span className="text-xl font-black">
          {formatMoney(p.amount, currency)}
        </span>
      </div>

      <p className="mt-3">
        {ctx.balanceAfter > 0
          ? `Balance outstanding as of ${ctx.asOf}: ${formatMoney(ctx.balanceAfter, currency)}`
          : `All dues paid as of ${ctx.asOf}.`}
      </p>
      {state === 'pending' && <p className="mt-1 italic">This cheque counts as paid once it clears.</p>}

      <footer className="mt-10 flex items-end justify-between gap-6">
        <div className="text-[10px] text-gray-600">Generated by Rent Tracker</div>
        <div className="text-center">
          <div className="w-44 border-t border-black pt-1">Received by / Signature</div>
        </div>
      </footer>
    </article>
  );
}
