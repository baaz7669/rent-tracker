import type { LandlordDetails, Unit } from '../types';
import type { Statement } from '../logic/statement';
import { formatMoney, formatAmount } from '../logic/format';

type Props = {
  unit: Unit;
  statement: Statement;
  currency: string;
  landlord?: LandlordDetails;
};

const fmtIn = (currency: string) => (n: number) => (n === 0 ? '' : formatAmount(n, currency));

/** Tenant account statement (A4). Plain black-on-white for printing and PDF. */
export function StatementDocument({ unit, statement, currency, landlord }: Props) {
  const fmt = fmtIn(currency);
  const closing = statement.closingBalance;
  return (
    <article className="statement-doc bg-white text-black font-sans text-[11px] leading-snug p-6 max-w-[210mm] mx-auto">
      <header className="flex items-start justify-between gap-4 pb-3 border-b-2 border-black">
        <div>
          <div className="text-base font-black">{landlord?.name || 'Rent Statement'}</div>
          {landlord?.address && <div className="whitespace-pre-line">{landlord.address}</div>}
          {landlord?.phone && <div>Tel: {landlord.phone}</div>}
        </div>
        <div className="text-right">
          <div className="text-lg font-black tracking-wide">STATEMENT OF ACCOUNT</div>
          <div>As of {statement.asOf}</div>
        </div>
      </header>

      <dl className="mt-3 grid grid-cols-[auto_1fr] gap-x-4 gap-y-1">
        <dt className="font-semibold">Tenant</dt>
        <dd>{unit.tenant}</dd>
        <dt className="font-semibold">Property</dt>
        <dd>
          {unit.building} · {unit.name}
        </dd>
        <dt className="font-semibold">Tenancy</dt>
        <dd>
          From {unit.firstDue}
          {unit.endedAt ? ` to ${unit.endedAt}` : ''} · {formatMoney(unit.rent, currency)} every{' '}
          {unit.every === 1 ? 'month' : `${unit.every} months`}
        </dd>
      </dl>

      <table className="mt-4 w-full border-collapse">
        <thead>
          <tr className="border-b border-black text-left">
            <th className="py-1 pr-2 font-semibold">Date</th>
            <th className="py-1 pr-2 font-semibold">Description</th>
            <th className="py-1 pr-2 font-semibold text-right">Due ({currency})</th>
            <th className="py-1 pr-2 font-semibold text-right">Paid ({currency})</th>
            <th className="py-1 font-semibold text-right">Balance</th>
          </tr>
        </thead>
        <tbody>
          {statement.lines.length === 0 ? (
            <tr>
              <td colSpan={5} className="py-3 text-center text-gray-600">
                Nothing has fallen due yet.
              </td>
            </tr>
          ) : (
            statement.lines.map((l, i) => (
              <tr key={i} className="border-b border-gray-300 align-top">
                <td className="py-1 pr-2 font-mono whitespace-nowrap">{l.date}</td>
                <td className="py-1 pr-2">{l.description}</td>
                <td className="py-1 pr-2 text-right">{fmt(l.charge)}</td>
                <td className="py-1 pr-2 text-right">{fmt(l.payment)}</td>
                <td className="py-1 text-right font-semibold">{formatAmount(l.balance, currency)}</td>
              </tr>
            ))
          )}
        </tbody>
        <tfoot>
          <tr className="border-t-2 border-black font-bold">
            <td className="py-1.5" colSpan={2}>
              Totals
            </td>
            <td className="py-1.5 pr-2 text-right">{formatAmount(statement.totalCharged, currency)}</td>
            <td className="py-1.5 pr-2 text-right">{formatAmount(statement.totalPaid, currency)}</td>
            <td className="py-1.5 text-right">{formatAmount(closing, currency)}</td>
          </tr>
        </tfoot>
      </table>

      <div className="mt-4 flex justify-end">
        <div className="border-2 border-black rounded-md px-4 py-2 text-right">
          <div className="font-semibold">
            {closing > 0 ? 'Balance outstanding' : closing < 0 ? 'Tenant in credit' : 'Balance'}
          </div>
          <div className="text-xl font-black">
            {formatMoney(Math.abs(closing), currency)}
          </div>
        </div>
      </div>

      {statement.pendingCheques.length > 0 && (
        <section className="mt-4">
          <h4 className="font-semibold">Cheques awaiting clearance (not included above)</h4>
          <ul className="mt-1">
            {statement.pendingCheques.map((c, i) => (
              <li key={i}>
                {c.date} · {c.description} · {formatMoney(c.amount, currency)}
              </li>
            ))}
          </ul>
        </section>
      )}

      <footer className="mt-8 text-[10px] text-gray-600 flex justify-between">
        <span>Generated by Rent Tracker</span>
        <span>Please contact us if anything on this statement looks wrong.</span>
      </footer>
    </article>
  );
}
